// Uses an isolated browser profile and synthetic learning records.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { expect } = require((process.env.PLAYWRIGHT_MODULE || 'playwright') + '/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.DRILL_TEST_URL || 'http://127.0.0.1:4174';
const key = 'business-english-drill:v1';
(async () => {
  const browser = await chromium.launch({ channel:'msedge', headless:true });
  const context = await browser.newContext({ viewport:{ width:390,height:844 }, permissions:['clipboard-read','clipboard-write'] });
  const page = await context.newPage(); const errors=[];
  page.on('pageerror', e => errors.push(e.message));
  const state = () => page.evaluate(k => JSON.parse(localStorage.getItem(k)),key);
  const expand = text => page.getByText(text,{exact:true}).click();
  const materials = async () => { if(!await page.locator('.short-materials').getAttribute('open').then(v=>v!==null)) await expand('换一段 / 导入我的教材样板'); };
  const noOverflow = async () => assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  try {
    await page.goto(base); await page.waitForLoadState('networkidle');
    await expect(page.getByRole('heading',{level:1})).toHaveText('More sales, less profit?');
    await expect(page.locator('.short-body')).toBeVisible();
    await expect(page.locator('textarea:visible')).toHaveCount(0);
    await page.evaluate(k => {
      const d=JSON.parse(localStorage.getItem(k));
      d.phrases=[{id:'old-phrase',phrase:'Keep this',category:'Align',example:'Legacy example',note:'My old note',savedAt:'2026-09-23'}];
      d.readings=[{id:'old-reading',title:'Old book',topic:'Work',source:'p.2',text:'Old passage',note:'Old reading note',savedAt:'2026-09-23'}];
      localStorage.setItem(k,JSON.stringify(d));
    },key);
    await page.reload(); await materials();
    const initial = await state();
    await page.getByLabel('选择短阅读资料包（JSON）').setInputFiles({ name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"broken":true}') });
    await expect(page.locator('.short-materials [role=status]')).toContainText('格式不完整');
    assert.deepEqual(await state(),initial);
    await page.getByLabel('选择短阅读资料包（JSON）').setInputFiles('personal-materials/bec-higher-module-1.json');
    await expect(page.getByRole('heading',{level:1})).toHaveText('What do young workers expect?');
    await noOverflow();
    await page.screenshot({path:'test-results/short-reading-mobile.png',fullPage:true});
    await expand('读前看一眼 · 4 个关键词');
    await expect(page.locator('.short-support dl')).toContainText('be entitled to');
    await expand('这句不明白 · 带着上下文问 Evan');
    await page.getByLabel('选择卡住的句子').selectOption({index:1});
    await page.getByLabel('哪里不明白？').fill('这里的 entitled 是什么意思？');
    await page.getByRole('button',{name:'复制句子、上下文和出处'}).click();
    await expect(page.locator('.question-support [role=status]')).toContainText('已复制');
    const copied=await page.evaluate(()=>navigator.clipboard.readText());
    assert.ok(copied.includes('PDF 第11页') && copied.includes('原文上下文') && copied.includes('这里的 entitled'));
    // Touch users can use the sentence selector; native text selection is supported too.
    await page.evaluate(() => { const n=document.querySelector('.short-body p').firstChild; const r=document.createRange(); r.setStart(n,0); r.setEnd(n,7); const s=getSelection(); s.removeAllRanges(); s.addRange(r); document.dispatchEvent(new Event('selectionchange')); });
    await expect(page.locator('.short-quote')).toHaveText('DETROIT');
    await page.evaluate(()=>Object.defineProperty(navigator.clipboard,'writeText',{configurable:true,value:()=>Promise.reject(new Error('denied'))}));
    await page.getByRole('button',{name:'复制句子、上下文和出处'}).click();
    await expect(page.getByLabel('手动复制提问')).toContainText('DETROIT');
    await noOverflow();
    await expand('想留下一个表达？看原句再收藏');
    await page.getByRole('button',{name:'收藏这个表达',exact:true}).first().click();
    assert.equal((await state()).phrases.length,2);
    assert.equal((await state()).phrases[1].learningState,undefined);
    await page.getByRole('button',{name:'今天读到这里',exact:true}).click();
    const completed=await state();
    assert.ok(completed.shortReadingProgress[completed.activeShortReading].lastRead);
    assert.equal(completed.shortReadingProgress[completed.activeShortReading].imitation,'');
    assert.deepEqual(completed.phrases[0],initial.phrases[0]);
    assert.deepEqual(completed.readings,initial.readings);
    await materials();
    await page.getByLabel('选择短阅读资料包（JSON）').setInputFiles('personal-materials/bec-higher-module-1.json');
    assert.equal((await state()).shortReadings.length,1);
    assert.deepEqual((await state()).shortReadingProgress,completed.shortReadingProgress);
    await page.evaluate(()=>navigator.serviceWorker.ready);
    await page.reload(); await page.waitForLoadState('networkidle');
    await context.setOffline(true); await page.reload();
    await expect(page.getByRole('heading',{level:1})).toHaveText('What do young workers expect?');
    assert.deepEqual((await state()).shortReadingProgress,completed.shortReadingProgress);
    await context.setOffline(false);
    await page.setViewportSize({width:320,height:740}); await noOverflow();
    await page.setViewportSize({width:1280,height:900});
    await page.screenshot({path:'test-results/short-reading-desktop.png',fullPage:true});
    await expand('想读更多？打开完整阅读书架');
    await page.getByRole('button',{name:'Open When sales rise but margins fall.',exact:true}).click();
    await expect(page.locator('.reading-body')).toBeVisible();
    assert.deepEqual(errors,[]);
    console.log('PASS: private import, invalid-file recovery, selection/copy/fallback, save, completion, preserved old records, repeat import, offline reload and responsive layout.');
  } finally { await browser.close(); }
})().catch(e=>{ console.error(e);process.exitCode=1; });
